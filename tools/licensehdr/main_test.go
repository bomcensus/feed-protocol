func write(t *testing.T, root, rel, content string, mode os.FileMode) string {
	t.Helper()
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), mode); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(p, mode); err != nil {
		t.Fatal(err)
	}
	return p
}

func read(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func fixOne(t *testing.T, root string) {
	t.Helper()
	if _, err := run([]string{root}, true, &bytes.Buffer{}); err != nil {
		t.Fatal(err)
	}
}

func TestStyles(t *testing.T) {
	const spdx = "SPDX-License-Identifier: Apache-2.0"
	cases := []struct{ name, body, wantPrefix string }{
		{"a.go", "package a\n", "// Copyright (C) 2026 JC-Lab\n// " + spdx + "\n\npackage a\n"},
		{"a.ts", "export {}\n", "// Copyright"},
		{"a.mjs", "export {}\n", "// Copyright"},
		{"a.yaml", "a: 1\n", "# Copyright"},
		{"a.ps1", "param()\n", "# Copyright"},
		{"Makefile", "all:\n", "# Copyright"},
		{"Dockerfile", "FROM x\n", "# Copyright"},
		{"a.sql", "select 1;\n", "-- Copyright"},
		{"a.vue", "<script setup lang=\"ts\">\n</script>\n", "<!--\n  Copyright (C) 2026 JC-Lab\n  " + spdx + "\n-->\n\n<script setup"},
		{"a.css", "a{}\n", "/*\n * Copyright (C) 2026 JC-Lab\n * " + spdx + "\n */\n\na{}\n"},
		{"a.html", "<!doctype html>\n<p>\n", "<!doctype html>\n<!--\n  Copyright"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			root := t.TempDir()
			p := write(t, root, c.name, c.body, 0o644)
			fixOne(t, root)
			got := read(t, p)
			if !strings.HasPrefix(got, c.wantPrefix) {
				t.Fatalf("got:\n%s", got)
			}
			if !strings.HasSuffix(got, c.body[strings.Index(c.body, "\n")+1:]) {
				t.Fatalf("body lost:\n%s", got)
			}
		})
	}
}

func TestShebang(t *testing.T) {
	root := t.TempDir()
	p := write(t, root, "run.sh", "#!/bin/sh\necho hi\n", 0o755)
	q := write(t, root, "tool", "#!/usr/bin/env bash\necho hi\n", 0o755)
	r := write(t, root, "plain", "just text\n", 0o644)
	fixOne(t, root)
	for _, f := range []string{p, q} {
		got := read(t, f)
		if !strings.HasPrefix(got, "#!") || !strings.Contains(strings.SplitN(got, "\n", 3)[1], "# Copyright") {
			t.Fatalf("%s:\n%s", f, got)
		}
		// Windows has no execute bit to keep.
		if st, _ := os.Stat(f); runtime.GOOS != "windows" && st.Mode().Perm() != 0o755 {
			t.Fatalf("mode changed: %v", st.Mode())
		}
	}
	if read(t, r) != "just text\n" {
		t.Fatal("extensionless non-script changed")
	}
}

func TestIdempotentAndCheck(t *testing.T) {
	root := t.TempDir()
	p := write(t, root, "a.go", "package a\n", 0o644)
	var out bytes.Buffer
	n, err := run([]string{root}, false, &out)
	if err != nil || n != 1 || !strings.Contains(out.String(), "a.go") {
		t.Fatalf("check: n=%d err=%v out=%q", n, err, out.String())
	}
	if read(t, p) != "package a\n" {
		t.Fatal("check modified file")
	}
	fixOne(t, root)
	first := read(t, p)
	fixOne(t, root)
	if read(t, p) != first {
		t.Fatal("not idempotent")
	}
	if n, _ := run([]string{root}, false, &bytes.Buffer{}); n != 0 {
		t.Fatalf("still missing: %d", n)
	}
}

func TestCRLF(t *testing.T) {
	root := t.TempDir()
	p := write(t, root, "a.go", "package a\r\n\r\nfunc f() {}\r\n", 0o644)
	fixOne(t, root)
	got := read(t, p)
	if strings.Count(got, "\n") != strings.Count(got, "\r\n") {
		t.Fatalf("mixed line endings: %q", got)
	}
}

func TestSkips(t *testing.T) {
	root := t.TempDir()
	skipped := map[string]string{
		"gen.go":              "// Code generated by x. DO NOT EDIT.\npackage a\n",
		"internal/gen/x/x.go": "package x\n",
		"node_modules/p/i.js": "x\n",
		".nuxt/a.ts":          "x\n",
		".output/a.js":        "x\n",
		"dist/a.js":           "x\n",
		"bin/a.sh":            "x\n",
		".devstate/a.sh":      "x\n",
		"testdata/a.go":       "package a\n",
		"LICENSES/a.yaml":     "a: 1\n",
		"go.sum":              "x\n",
		"pnpm-lock.yaml":      "x: 1\n",
		"README.md":           "x\n",
		"a.json":              "{}\n",
		"a.png":               "x",
		"a.woff2":             "x",
		"LICENSE":             "x\n",
		".gitignore":          "x\n",
		".nvmrc":              "26\n",
		"go.mod":              "module x\n",
		"has.go":              "// Copyright (C) 2020 X\n// SPDX-License-Identifier: Apache-2.0\npackage a\n",
	}
	for p, c := range skipped {
		write(t, root, p, c, 0o644)
	}
	var out bytes.Buffer
	n, err := run([]string{root}, false, &out)
	if err != nil || n != 0 {
		t.Fatalf("n=%d err=%v out=%s", n, err, out.String())
	}
}

func TestHelmTemplate(t *testing.T) {
	root := t.TempDir()
	tpl := write(t, root, "deploy/charts/bc/templates/deployment.yaml", "apiVersion: v1\n", 0o644)
	hlp := write(t, root, "deploy/charts/bc/templates/_helpers.tpl", "{{- define \"x\" -}}y{{- end -}}\n", 0o644)
	notes := write(t, root, "deploy/charts/bc/templates/NOTES.txt", "hello\n", 0o644)
	vals := write(t, root, "deploy/charts/bc/values.yaml", "a: 1\n", 0o644)
	fixOne(t, root)
	for _, f := range []string{tpl, hlp, notes} {
		got := read(t, f)
		if !strings.HasPrefix(got, "{{- /*\n  Copyright (C) 2026 JC-Lab\n") || !strings.Contains(got, "\n*/ -}}\n") {
			t.Fatalf("%s:\n%s", f, got)
		}
	}
	if !strings.HasPrefix(read(t, vals), "# Copyright") {
		t.Fatalf("values.yaml:\n%s", read(t, vals))
	}
	before := read(t, tpl)
	fixOne(t, root)
	if read(t, tpl) != before {
		t.Fatal("not idempotent")
	}
}
